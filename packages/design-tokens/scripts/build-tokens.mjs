import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import StyleDictionary from "style-dictionary";

const PACKAGE_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const REPOSITORY_ROOT = join(PACKAGE_ROOT, "..", "..");
const BUILD_COMMAND = "pnpm --filter @fnb/design-tokens build";
const THEMES = ["light", "dark", "print"];
const THEME_WRAPPERS = {
	light: null,
	dark: "@media (prefers-color-scheme: dark)",
	print: "@media print",
};

export const GENERATED_FILES = {
	css: join(PACKAGE_ROOT, "src", "generated", "tokens.css"),
	ts: join(PACKAGE_ROOT, "src", "generated", "palette.ts"),
};

async function themeTokens(theme) {
	const dictionary = new StyleDictionary({
		source: [
			join(PACKAGE_ROOT, "tokens", `color.${theme}.tokens.json`),
			join(PACKAGE_ROOT, "tokens", "font.tokens.json"),
		],
		log: { verbosity: "silent", warnings: "disabled" },
		platforms: { web: { transformGroup: "css" } },
	});
	const { allTokens } = await dictionary.getPlatformTokens("web");
	return allTokens;
}

function colorEntries(tokens) {
	return tokens
		.filter((token) => token.path[0] === "color")
		.map((token) => [token.path.slice(1).join("-"), String(token.$value)]);
}

function fontEntries(tokens) {
	return tokens
		.filter((token) => token.path[0] === "font")
		.map((token) => [
			token.path.slice(1).join("-"),
			String(token.$value).replaceAll("'", '"'),
		]);
}

function cssBlock(selector, declarations, wrapper) {
	const body = declarations.map(([name, value]) => `--${name}: ${value};`);
	const root = `${selector} {\n${body.map((line) => `\t${line}`).join("\n")}\n}`;
	if (wrapper === null) return root;
	return `${wrapper} {\n${root
		.split("\n")
		.map((line) => `\t${line}`)
		.join("\n")}\n}`;
}

function formatWithBiome(source, path) {
	return execFileSync(
		join(REPOSITORY_ROOT, "node_modules", ".bin", "biome"),
		["format", `--stdin-file-path=${path}`],
		{ input: source, encoding: "utf8", cwd: REPOSITORY_ROOT },
	);
}

export async function renderTokenFiles() {
	const themes = Object.fromEntries(
		await Promise.all(
			THEMES.map(async (theme) => [theme, await themeTokens(theme)]),
		),
	);
	const light = themes.light;
	const fonts = fontEntries(light);
	const blocks = THEMES.map((theme) =>
		cssBlock(":root", colorEntries(themes[theme]), THEME_WRAPPERS[theme]),
	);
	const themeMapping = cssBlock(
		"@theme inline",
		[
			...colorEntries(light).map(([name]) => [
				`color-${name}`,
				`var(--${name})`,
			]),
			...fonts.map(([name, value]) => [`font-${name}`, value]),
		],
		null,
	);
	const cssSource = [
		`/* Generated by ${BUILD_COMMAND} from packages/design-tokens/tokens; do not edit. */`,
		...blocks,
		themeMapping,
	].join("\n\n");
	const palette = THEMES.map((theme) => {
		const entries = colorEntries(themes[theme])
			.map(
				([name, value]) =>
					`\t\t${JSON.stringify(name)}: ${JSON.stringify(value)},`,
			)
			.join("\n");
		return `\t${theme}: {\n${entries}\n\t},`;
	}).join("\n");
	const fontStacks = fonts
		.map(
			([name, value]) => `\t${JSON.stringify(name)}: ${JSON.stringify(value)},`,
		)
		.join("\n");
	const tsSource = [
		`// Generated by ${BUILD_COMMAND} from packages/design-tokens/tokens; do not edit.`,
		`export const colors = {\n${palette}\n} as const;`,
		`export const fontStacks = {\n${fontStacks}\n} as const;`,
		"export type ColorTheme = keyof typeof colors;",
		'export type ColorName = keyof (typeof colors)["light"];',
		"",
	].join("\n\n");
	return {
		css: formatWithBiome(`${cssSource}\n`, GENERATED_FILES.css),
		ts: formatWithBiome(tsSource, GENERATED_FILES.ts),
	};
}

async function main() {
	const check = process.argv.includes("--check");
	const rendered = await renderTokenFiles();
	const stale = [];
	for (const [kind, path] of Object.entries(GENERATED_FILES)) {
		if (check) {
			const current = await readFile(path, "utf8").catch(() => "");
			if (current !== rendered[kind]) stale.push(path);
		} else {
			await writeFile(path, rendered[kind]);
		}
	}
	if (stale.length > 0) {
		console.error(`Out of date, run ${BUILD_COMMAND}: ${stale.join(", ")}`);
		process.exitCode = 1;
	} else {
		console.log(
			check
				? "design tokens: generated files are current"
				: "design tokens: generated files written",
		);
	}
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) await main();
