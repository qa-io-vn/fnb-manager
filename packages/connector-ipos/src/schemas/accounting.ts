import { z } from "zod";
import {
	epochMs,
	money,
	optionalMoney,
	optionalNumber,
	optionalText,
} from "./common.js";

const invoiceHeaderShape = {
	tran_id: z.string(),
	tran_no: optionalText,
	tran_date: epochMs,
	start_hour: optionalNumber,
	start_minute: optionalNumber,
	end_hour: optionalNumber,
	end_minute: optionalNumber,
	table_name: optionalText,
	area_id: optionalText,
	area_name: optionalText,
	sale_type: optionalText,
	source_id: optionalText,
	source_name: optionalText,
	shift_id: optionalText,
	store_uid: optionalText,
	employee_id: optionalText,
	employee_name: optionalText,
	customer_name: optionalText,
	customer_phone: optionalText,
	peo_count: optionalNumber,
	payment_method_id: optionalText,
	payment_method_name: optionalText,
	pos_id: optionalNumber,
};

export const invoiceSchema = z.looseObject({
	...invoiceHeaderShape,
	total_amount: money,
	amount_origin: money,
	amount_discount_detail: optionalMoney,
	amount_discount_price: optionalMoney,
	discount_extra_amount: optionalMoney,
	discount_extra_name: optionalText,
	voucher_code: optionalText,
	voucher_name: optionalText,
	voucher_amount_paid: optionalMoney,
	vat_amount: optionalMoney,
	ship_fee_amount: optionalMoney,
	service_charge_amount: optionalMoney,
	commission_amount: optionalMoney,
	partner_marketing_amount: optionalMoney,
});

export const invoiceLineSchema = z.looseObject({
	...invoiceHeaderShape,
	id: z.string(),
	sale_id: optionalText,
	item_id: z.string(),
	item_name: z.string(),
	item_type_id: optionalText,
	item_type_name: optionalText,
	item_class_id: optionalText,
	item_class_name: optionalText,
	unit_id: optionalText,
	quantity: z.number(),
	price: money,
	ots_price: optionalMoney,
	amount: money,
	discount_amount: optionalMoney,
	amount_discount_on_price: optionalMoney,
	index: optionalNumber,
	promotion_id: optionalText,
	promotion_name: optionalText,
	item_note: optionalText,
	package_id: optionalText,
	sale_detail_type: optionalNumber,
	total_amount: optionalMoney,
	vat_tax_amount: optionalMoney,
	vat_tax_rate: optionalNumber,
	voucher_amount: optionalMoney,
});

export const paymentSchema = z.looseObject({
	tran_id: z.string(),
	tran_no: optionalText,
	tran_date: epochMs,
	store_uid: optionalText,
	payment_method_id: z.string(),
	payment_method_name: optionalText,
	amount: money,
	total_amount: optionalMoney,
	payment_fee_amount: optionalMoney,
	payment_fee: optionalNumber,
	trace_no: optionalText,
	tran_id_of_partner: optionalText,
	customer_name: optionalText,
	customer_phone: optionalText,
	customer_id: optionalText,
	employee_id: optionalText,
	employee_name: optionalText,
});

export const dailySalesSchema = z.looseObject({
	tran_date: epochMs,
	date: optionalText,
	total_amount: money,
	total_sales: optionalNumber,
	amount_origin: optionalMoney,
	vat_amount: optionalMoney,
	ship_fee_amount: optionalMoney,
	voucher_amount_paid: optionalMoney,
	service_charge_amount: optionalMoney,
	commission_amount: optionalMoney,
	amount_discount_price: optionalMoney,
	amount_discount_detail: optionalMoney,
	discount_extra_amount: optionalMoney,
	peo_count: optionalNumber,
	payment_method_name: optionalText,
});

export type Invoice = z.infer<typeof invoiceSchema>;
export type InvoiceLine = z.infer<typeof invoiceLineSchema>;
export type Payment = z.infer<typeof paymentSchema>;
export type DailySales = z.infer<typeof dailySalesSchema>;
